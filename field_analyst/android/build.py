"""Reproducible Android SDK CLI build: no Gradle/network dependencies.
Builds RECORDS-ONLY development APK; analysis integration is explicitly blocked.
"""
import argparse, hashlib, json, os, shutil, subprocess, sys, zipfile
from pathlib import Path

def main():
    p=argparse.ArgumentParser();p.add_argument('--sdk',default=os.environ.get('ANDROID_HOME') or os.environ.get('ANDROID_SDK_ROOT'));p.add_argument('--build-tools',default='35.0.1');a=p.parse_args()
    sdk=Path(a.sdk) if a.sdk else Path(os.environ.get('LOCALAPPDATA',''))/'Android'/'Sdk'
    sdk=sdk.resolve();root=Path(__file__).resolve().parent;out=root/'build';out.mkdir(exist_ok=True)
    tools=sdk/'build-tools'/a.build_tools;android=sdk/'platforms'/'android-35'/'android.jar'
    ext='.exe' if os.name=='nt' else '';bat='.bat' if os.name=='nt' else ''
    def run(args):
        args=[str(x) for x in args]; print('RUN '+repr(args),flush=True)
        subprocess.run(args,check=True,stderr=subprocess.STDOUT)
    for tool in ('javac','keytool'):
        if not shutil.which(tool): raise RuntimeError(f'Missing {tool}; install JDK 21')
    if not android.exists(): raise RuntimeError('Android SDK platform 35 missing')
    classes=out/'classes';classes.mkdir(exist_ok=True);dex=out/'dex';dex.mkdir(exist_ok=True)
    # Strip UTF-8 BOM from Java/XML source generated by Windows tools.
    for path in [*root.glob('src/**/*.java'),root/'AndroidManifest.xml',*root.glob('res/**/*.xml')]:
        data=path.read_bytes()
        if data.startswith(b'\xef\xbb\xbf'):path.write_bytes(data[3:])
    run([tools/('aapt'+ext),'package','-f','-M',root/'AndroidManifest.xml','-S',root/'res','-A',root/'assets','-I',android,'-F',out/'resources.apk'])
    run(['javac','-encoding','UTF-8','--release','8','-classpath',android,'-d',classes,*root.glob('src/**/*.java')])
    run([tools/('d8'+bat),'--lib',android,'--min-api','26','--output',dex,*classes.glob('**/*.class')])
    shutil.copyfile(out/'resources.apk',out/'unsigned.apk')
    with zipfile.ZipFile(out/'unsigned.apk','a',compression=zipfile.ZIP_DEFLATED) as archive:
        archive.write(dex/'classes.dex','classes.dex')
    run([tools/('zipalign'+ext),'-f','4',out/'unsigned.apk',out/'aligned.apk'])
    key=out/'debug.keystore'
    if not key.exists():run(['keytool','-genkeypair','-keystore',key,'-storepass','android','-alias','androiddebugkey','-keypass','android','-dname','CN=Android Debug,O=Android,C=US','-keyalg','RSA','-keysize','2048','-validity','10000'])
    apk=out/'cne-field-analyst-records-debug.apk'
    run([tools/('apksigner'+bat),'sign','--ks',key,'--ks-key-alias','androiddebugkey','--ks-pass','pass:android','--key-pass','pass:android','--out',apk,out/'aligned.apk'])
    run([tools/('apksigner'+bat),'verify','--verbose',apk]);run([tools/('aapt'+ext),'dump','badging',apk]);run([tools/('aapt'+ext),'dump','permissions',apk])
    with zipfile.ZipFile(apk) as archive:
        names=archive.namelist()
        if any(n.endswith(('.pt','.onnx','.tflite','.so')) for n in names):raise RuntimeError('Unexpected model/runtime in records-only build')
    apk_hash=hashlib.sha256()
    with apk.open('rb') as source:
        for chunk in iter(lambda:source.read(1024*1024),b''):apk_hash.update(chunk)
    report={'status':'BUILT_RECORDS_ONLY','apk':str(apk),'sha256':apk_hash.hexdigest(),'bytes':apk.stat().st_size,
            'package':'org.cne.fieldanalyst','min_sdk':26,'target_sdk':35,'build_tools':a.build_tools,'jdk':subprocess.check_output(['javac','-version'],stderr=subprocess.STDOUT,text=True).strip(),
            'gradle':'not used: direct aapt/javac/d8/zipalign/apksigner SDK build','abis':'Java-only DEX; no native inference runtime','signing':'local debug key, not for release',
            'model_included':False,'runtime_included':False,'cne_bridge':'BLOCKED','device_test':'NOT_TESTED','permissions':[],'members':names}
    (root.parent/'reports'/'android-build.json').write_text(json.dumps(report,indent=2),encoding='utf8');print(json.dumps(report,indent=2))
if __name__=='__main__':main()
